def 找名詞(文字):
    """文字裡第一個出現的名詞小卡關鍵字（含別名）。"""
    文字 = str(文字)
    for k in list(名詞卡) + list(_別名):
        if re.search(rf"(?<![A-Za-z]){re.escape(k)}(?![A-Za-z])", 文字):
            return _別名.get(k, k)
    return None


def 小卡HTML(詞):
    """❓ 懸停／點一下顯示三欄說明（純 CSS，手機點一下也會打開）。"""
    白, 用, 坑 = 名詞卡[詞]
    e = html.escape
    return (f'<span class="tip" tabindex="0">❓<span class="tipbox"><b>{e(詞)}</b>'
            f'<i>白話是什麼</i>{e(白)}<i>這數字怎麼用</i>{e(用)}<i>新手常見陷阱</i>{e(坑)}</span></span>')


def _燈(等級):
    return {"熱": "🔥", "多": "🟢", "中": "🟡", "空": "🔴", "冷": "🧊"}[等級]


def 白話燈號(r, 均線們=None, 估值百分位=None, rs=None):
    """把冷冰冰的指標翻成新手看得懂的一句話。r＝今日資料的一列；均線們＝{5: 價, 20: 價, 60: 價}（原始股價刻度）。
    回傳 [(燈, 標題, 白話, 建議), …]，最重要的排前面。注意：台股紅漲綠跌，這裡的燈號顏色是「行動建議」不是漲跌。"""
    結果 = []
    收 = float(r.get("收盤") or np.nan)
    rsi = r.get("RSI")
    ma20 = (均線們 or {}).get(20)
    乖離 = (收 / ma20 - 1) * 100 if ma20 and np.isfinite(收) and ma20 > 0 else np.nan
    數字 = "、".join(x for x in (f"RSI {rsi:.0f}" if pd.notna(rsi) else "",
                               f"離 20 日線 {乖離:+.0f}%" if pd.notna(乖離) else "") if x)
    if (pd.notna(rsi) and rsi >= 75) or (pd.notna(乖離) and 乖離 >= 12):
        結果.append(("熱", "短期漲幅過熱",
                   f"{數字}：股價衝太快（像跑百米剛衝過終點），短線追高容易遇到拉回休息。",
                   "新手建議等拉回到 10 日或 20 日線附近、量縮止穩再觀察。"))
    elif (pd.notna(rsi) and rsi <= 25) or (pd.notna(乖離) and 乖離 <= -12):
        結果.append(("冷", "短期跌太兇",
                   f"{數字}：賣壓很重，像溜滑梯溜太快，可能會有反彈。",
                   "反彈不等於回升，新手別急著接刀；等出現止跌紅 K、站回 5 日線再說。"))
    if 均線們 and all(均線們.get(n) for n in (5, 20, 60)) and np.isfinite(收):
        if 收 > 均線們[5] > 均線們[20] > 均線們[60]:
            結果.append(("多", "趨勢向上（多頭排列）", "短、中、長期的平均成本都在往上墊高，買進的人大多是賺錢的。",
                       "順勢的人會抱著，跌破 20 日線再減碼。"))
        elif 收 < 均線們[5] < 均線們[20] < 均線們[60]:
            結果.append(("空", "趨勢向下（空頭排列）", "短、中、長期買進的人大多在虧錢，每次反彈都會遇到解套賣壓。",
                       "新手先觀望，等站回 20 日線再研究。"))
        elif 收 > 均線們[20]:
            結果.append(("中", "站在月線上、方向還不明確", "股價在 20 日平均成本之上，但長短均線還沒排好。", "可以觀察，但部位放小。"))
        else:
            結果.append(("中", "在月線下整理", "股價低於近 20 天買進者的平均成本，上方有解套賣壓。", "等站回 20 日線再說。"))
    法 = r.get("法人5日買超")
    if pd.notna(法) and abs(法) > 0:
        if 法 > 0 and (r.get("外資連買", 0) >= 3 or r.get("投信連買", 0) >= 3):
            結果.append(("多", "大戶在買", f"外資或投信連續買超，近 5 日法人合計買 {法:,.0f} 張。", "有大錢撐腰，但仍要看股價有沒有跟著漲。"))
        elif 法 < 0 and (r.get("外資連賣", 0) >= 3):
            結果.append(("空", "大戶在賣", f"外資連續賣超，近 5 日法人合計賣 {-法:,.0f} 張。", "持股的人留意，跌破支撐要先減碼。"))
    if 估值百分位 is not None:
        if 估值百分位 >= 85:
            結果.append(("熱", "估值偏貴", f"本益比比過去 5 年 {估值百分位:.0f}% 的時間都高。", "要有獲利繼續成長才撐得住，財報不如預期跌幅會大。"))
        elif 估值百分位 <= 15:
            結果.append(("多", "估值便宜", f"本益比只比過去 5 年 {估值百分位:.0f}% 的時間高。", "便宜可能有原因，先確認營收、獲利沒有衰退。"))
    if rs is not None and pd.notna(rs):
        if rs >= 85:
            結果.append(("多", "強勢好學生", f"RS {rs:.0f}：近一年漲幅贏過 {rs:.0f}% 的股票。", "強者恆強，但已經漲很多，進場一定要設停損。"))
        elif rs <= 20:
            結果.append(("空", "弱勢股", f"RS {rs:.0f}：近一年表現落後大部分股票。", "便宜不等於會漲，弱勢股常常越跌越便宜。"))
    return [(_燈(a), b, c, d) for a, b, c, d in 結果]


def 一句話結論(燈們):
    """多個燈號 → 新手一句話：該買、該等、還是該跑。"""
    if not 燈們:
        return "🟡 資料不足，先觀察就好。"
    熱 = sum(1 for x in 燈們 if x[0] == "🔥")
    多 = sum(1 for x in 燈們 if x[0] == "🟢")
    空 = sum(1 for x in 燈們 if x[0] == "🔴")
    if 空 >= 2 or (空 and not 多):
        return "🔴 先跑或先別碰：趨勢或籌碼偏弱，等轉強訊號出現再研究。"
    if 熱 and 多:
        return "🔥 好股票但太熱：趨勢向上，可是短線衝太快，新手等拉回再買，不要追高。"
    if 多 >= 2:
        return "🟢 可以研究買點：趨勢與籌碼偏多，進場前先想好停損價。"
    return "🟡 先等等：訊號不一致，放進自選股觀察，等方向明確。"


