"""2026-11-25：庫藏股新決議（近 3 個交易日）清單、最多花、佔市值，與新決議後報酬回測。"""
import numpy as np
import pandas as pd

import engine


def _庫():
    return pd.DataFrame({
        "code": ["5351", "3218", "3680", "2486", "9999"], "name": ["鈺創", "大學光", "家登", "一詮", "舊的"],
        "board_date": pd.to_datetime(["2026-11-24", "2026-11-24", "2026-11-23", "2026-11-20", "2026-11-10"]),
        "purpose": [1, 3, 1, 1, 3], "planned": [5e6, 2.5e6, 3e6, 1.5e6, 1e6],
        "price_low": [61, 100, 240, 100, 10], "price_high": [146, 190, 450, 200, 20],
        "start": pd.to_datetime(["2026-11-25"] * 5), "end": pd.to_datetime(["2027-01-22"] * 5),
        "done": ["N"] * 5, "pct_done": [np.nan] * 5})


def test_新決議只取近三個交易日且算最多花():
    日 = pd.to_datetime(["2026-11-19", "2026-11-20", "2026-11-23", "2026-11-24"])
    現 = pd.Series({"5351": 100.0, "3218": 95.0, "3680": 300.0, "2486": 150.0})
    股 = pd.Series({"5351": 2.8e8, "3218": 1e8, "3680": 1e8, "2486": 1e8})
    新 = engine.庫藏股新決議(_庫(), 日, 3, 現, 股)
    assert list(新["code"]) == ["5351", "3218", "3680", "2486"]   # 新的日期在前、同日最多花大的在前
    r = 新.iloc[0]
    assert r["目的"] == "員工" and r["張數"] == 5000 and round(r["最多花億"], 2) == 7.3
    assert round(r["佔市值%"], 2) == round(7.3e8 / (100 * 2.8e8) * 100, 2)
    assert 新.iloc[1]["目的"] == "護盤" and 新.iloc[1]["價位"].startswith("⚠️")


def test_新決議文字格式():
    日 = pd.to_datetime(["2026-11-20", "2026-11-23", "2026-11-24"])
    新 = engine.庫藏股新決議(_庫(), 日, 3)
    文 = engine.庫藏股新決議文字(新)
    assert "【11/24（二）2 件】" in 文
    assert "・鈺創 5351｜員工｜5,000 張｜61～146 元｜7.3 億" in 文
    assert "・家登 3680｜員工｜3,000 張｜240～450 元｜13.5 億" in 文
    assert "舊的" not in 文


def test_庫藏股回測分組():
    日 = pd.bdate_range("2026-01-01", periods=90)
    列 = []
    for c, 漲 in (("1111", 0.01), ("2222", 0.0), ("3333", -0.005)):
        價 = 10.0
        for d in 日:
            新價 = 價 * (1 + 漲)
            列.append({"code": c, "date": d, "open": 價, "high": 新價, "low": 價, "close": 新價, "change": 新價 - 價})
            價 = 新價
    原始 = pd.DataFrame(列)
    庫 = pd.DataFrame({"code": ["1111", "3333"], "name": ["甲", "丙"], "board_date": [日[5], 日[5]],
                      "purpose": [3, 1], "planned": [1e6, 1e6], "price_low": [5, 5], "price_high": [20, 20],
                      "start": [日[6]] * 2, "end": [日[50]] * 2, "done": ["Y", "Y"], "pct_done": [100.0, 30.0]})
    結 = engine.庫藏股回測(原始, 庫)
    組 = {x["條件"]: x for x in 結["分組"]}
    assert 組["全部新決議"]["次數"] == 2
    assert 組["護盤（維護公司信用）"]["20日超額%"] > 0 > 組["員工（轉讓員工）"]["20日超額%"]
