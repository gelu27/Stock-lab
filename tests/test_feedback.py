"""回饋循環（feedback.py）的單元測試：錯誤本、個股 AI 回顧、券商紀錄、規則體檢、週報自我檢討、額度文字、提示版本。"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import numpy as np
import pandas as pd

import engine
import feedback

失敗 = []


def 檢查(條件, 說明):
    print(("✅ " if 條件 else "❌ ") + 說明)
    if not 條件:
        失敗.append(說明)


# F1 大盤錯誤本
驗 = [{"鍵": f"k{i}", "時間": f"2026-11-{12 - i:02d} 08:10", "模式": "盤前", "看法": "偏空", "驗收日": pd.Timestamp(f"2026-11-{12 - i:02d}"),
      "加權漲跌%": 2.0, "看法對": False, "條件": [{"說明": "加權守住 1", "指數": "加權", "方向": "守住", "價位": 1, "收盤": 0.5, "成立": False}]}
     for i in range(4)]
驗.append({"鍵": "k9", "時間": "2026-11-01 08:10", "模式": "收盤", "看法": "偏多", "驗收日": pd.Timestamp("2026-11-02"),
          "加權漲跌%": 0.1, "看法對": True, "條件": []})
文 = feedback.大盤錯誤本(驗)
檢查("看法命中 1/5" in 文, "錯誤本：寫出命中率")
檢查("大幅看錯方向" in 文 and "偏空" in 文, "錯誤本：列出看錯的例子與錯因")
檢查("偏誤提醒" in 文 and "太悲觀" in 文, "錯誤本：看錯多半偏空時提醒太悲觀")
檢查("中性" in 文, "錯誤本：命中率低時建議改寫中性＋條件")
檢查(feedback.大盤錯誤本([]) == "", "錯誤本：沒有紀錄回傳空字串")

# F1 個股 AI 回顧
日 = pd.bdate_range("2026-10-01", periods=40)
價 = pd.DataFrame({"date": 日, "收盤": np.linspace(100, 80, 40)})
價["high"], 價["low"] = 價["收盤"] * 1.01, 價["收盤"] * 0.99
紀 = [{"時間": "2026-10-02 18:00", "資料日期": "2026-10-02", "收盤": 100,
      "建議": {"看法": "偏多", "目標價合理": 130, "停損": 90}, "內容": ""}]
回 = feedback.個股AI回顧(紀, 價)
檢查("先跌到停損價（看錯）" in 回 and "偏多" in 回, "個股回顧：偏多後跌破停損標示看錯")
檢查(feedback.個股AI回顧([], 價) == "", "個股回顧：沒有紀錄回傳空字串")

# F2 券商紀錄：看多後跑輸加權＝說錯；達標率只算滿 6 個月
加權 = pd.DataFrame({"date": 日, "close": np.linspace(100, 110, 40)})
報告們 = [{"代號": "1111", "券商": "甲投顧", "日期": "2026-10-01", "看法": "看多", "目標價": 200},
        {"代號": "1111", "券商": "甲投顧", "日期": "2026-10-02", "看法": "看空", "目標價": 70}]
表 = feedback.券商紀錄表(報告們, {"1111": 價}, 加權)
r = 表.loc["甲投顧"]
檢查(r["20日到期"] == 2 and r["20日說對%"] == 50, "券商紀錄：看多跑輸算錯、看空跑輸算對（50%）")
檢查(r["達標率%"] is None or pd.isna(r["達標率%"]), "券商紀錄：還沒滿 6 個月不算達標率")
文 = feedback.券商紀錄文字(表.to_dict("index"), ["甲投顧", "乙投顧"])
檢查("甲投顧" in 文 and "乙投顧" not in 文 and "樣本少" in 文, "券商紀錄文字：只列有紀錄的券商並標樣本少")
檢查(feedback.LINE券商紀錄短句(["甲投顧"], {"券商": 表.to_dict("index")}) == "", "LINE 短句：樣本不足不列")

# F4 規則體檢判定與變化
檢查(feedback._判定(0.5, 20) == "有效" and feedback._判定(-0.5, 20) == "反向" and feedback._判定(0.1, 20) == "沒有優勢"
     and feedback._判定(1, 3) == "樣本太少", "規則體檢：判定門檻")
列 = feedback._統計列("x", [{"天數": 5, "次數": 9, "平均%": 1, "基準平均%": 0.5},
                         {"天數": 20, "次數": 9, "平均%": 1, "基準平均%": 2}])
檢查(列["天數"] == 20 and 列["超額%"] == -1 and 列["判定"] == "反向", "規則體檢：取 20 日並扣基準")
體 = {"歷史": [{"計算日": "2026-10-12", "規則": [{"規則": "A", "判定": "有效", "超額%": 1, "天數": 20}]},
             {"計算日": "2026-11-12", "規則": [{"規則": "A", "判定": "沒有優勢", "超額%": 0.1, "天數": 20}]}]}
檢查(feedback.體檢變化(體) == [("A", "有效", "沒有優勢", 0.1)], "規則體檢：找出判定改變的規則")
檢查(any("有效→沒有優勢" in x for x in feedback.規則體檢文字(體)), "規則體檢月報：寫出變化")
檢查("A" in feedback.規則體檢文字(體, 給AI=True)[0], "規則體檢：給 AI 列出沒有優勢的燈號")

# F7 週報自我檢討
回饋 = {"大盤解讀": {"明細": [{"時間": "2026-11-10 08:10", "模式": "盤前", "看法": "偏多", "驗收日": "2026-11-10",
                          "加權漲跌%": -1.8, "看法對": False, "條件": [{"說明": "x", "成立": True}], "提示版本": "未記錄"}]},
       "AI報告": {"達標": 1, "停損": 1, "近期結案": [{"代號": "2330", "結果": "達標", "結案日": "2026-11-11"},
                                               {"代號": "2330", "結果": "達標", "結案日": "2026-11-11"}]}}
週 = "\n".join(feedback.週報自我檢討("2026-11-09", "2026-11-13", 回饋))
檢查("看法說對 0/1" in 週 and "大幅看錯方向" in 週, "週報：大盤解讀本週對答案")
檢查("達標 2 份（2330）" in 週, "週報：個股報告結案（同一檔不重複列）")
檢查(feedback.週報自我檢討("2026-01-01", "2026-01-02", 回饋) == [], "週報：這週沒有資料就不加段落")

# F6 額度文字
檢查("會超過免費上限" in feedback.額度文字({"上限": 10, "已用": 9}) or pd.Timestamp.now().day > 27,
     "額度：照速度會超過時警告")
檢查(feedback.額度文字(None) == "", "額度：查不到回傳空字串")

# F8 提示版本：同樣文字同版本、改字就換
檢查(engine.提示版本("a") == engine.提示版本("a") != engine.提示版本("b") and len(engine.大盤提示版本()) == 8,
     "提示版本：指紋 8 碼、改字就換")
檢查("回饋紀錄" in engine.大盤解讀提示 and "回饋紀錄" in engine.AI系統提示, "提示：加入回饋規則")

# F5 預估
檢查(feedback._預估到期(["2026-01-01"] * 5, 5, 10) == "已達到", "進度：門檻那筆＋延遲已過＝已達到")
檢查(feedback._預估到期([], 5, 10) == "還沒有樣本", "進度：沒有樣本")

if 失敗:
    print(f"\n{len(失敗)} 項失敗")
    sys.exit(1)
print("\n全部通過")
