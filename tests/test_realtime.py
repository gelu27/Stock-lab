# 自動檢查：個股報告盤中改用即時價（engine.套用即時價）
#   本機執行：python tests/test_realtime.py
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import engine  # noqa: E402

列 = pd.Series({"收盤": 100.0, "漲跌": 1.0, "漲跌幅": 1.0, "本益比": 20.0, "殖利率": 3.0, "淨值比": 2.0,
               "還原價": 95.0, "成交張數": 5000.0, "volume": 5_000_000.0, "市場": "上市", "名稱": "測試"})
資料日 = "2026-11-06"   # 週五


def 報價(價=110.0, 漲跌=10.0, 日="2026-11-09", 時="10:35:12"):
    return lambda 代號, 市場: pd.DataFrame([{"code": "9999", "close": 價, "change": 漲跌, "time": 時,
                                          "volume": 8000.0, "date": pd.Timestamp(日)}])


def main():
    錯誤 = []
    盤中 = pd.Timestamp("2026-11-09 10:36")
    新, 說明 = engine.套用即時價(列, "9999", 資料日, 現在=盤中, 抓報價=報價())
    if 說明 != "盤中 11/09 10:35 即時價":
        錯誤.append(f"說明文字不對：{說明}")
    預期 = {"收盤": 110, "漲跌": 10, "漲跌幅": 10, "本益比": 22, "殖利率": 3 / 1.1, "淨值比": 2.2, "還原價": 104.5,
          "成交張數": 8000}
    for k, v in 預期.items():
        if abs(float(新[k]) - v) > 0.01:
            錯誤.append(f"{k}：得到 {新[k]}，應該是 {v}")
    if abs(新["收盤"] / 新["還原價"] - 列["收盤"] / 列["還原價"]) > 1e-9:
        錯誤.append("收盤／還原價比例變了（均線換算會錯）")
    if 列["收盤"] != 100:
        錯誤.append("原本的列被改到了")

    _, 說明 = engine.套用即時價(列, "9999", 資料日, 現在=pd.Timestamp("2026-11-09 15:00"), 抓報價=報價(時="13:30:00"))
    if 說明 != "今日收盤 11/09 13:30 即時價":
        錯誤.append(f"收盤後說明不對：{說明}")

    def 不該抓(代號, 市場):
        raise AssertionError("不該上網抓")
    for 名, 現在, 日 in (("週日", "2026-11-08 10:00", 資料日), ("早上 9 點前", "2026-11-09 08:30", 資料日),
                        ("資料庫已是今天", "2026-11-09 19:00", "2026-11-09")):
        try:
            新, 說明 = engine.套用即時價(列, "9999", 日, 現在=pd.Timestamp(現在), 抓報價=不該抓)
        except AssertionError:
            錯誤.append(f"{名}：不該抓即時價")
            continue
        if 說明 or 新["收盤"] != 100:
            錯誤.append(f"{名}：不該改價格")

    _, 說明 = engine.套用即時價(列, "9999", 資料日, 現在=盤中, 抓報價=報價(日="2026-11-06"))
    if 說明:
        錯誤.append("即時價日期跟資料庫同一天，不該套用")
    _, 說明 = engine.套用即時價(列.copy().set_axis(列.index), "9999", 資料日, 現在=盤中, 抓報價=lambda c, m: 1 / 0)
    if 說明:
        錯誤.append("抓不到即時價時要維持原本的價格")
    興櫃 = 列.copy()
    興櫃["市場"] = "興櫃"
    _, 說明 = engine.套用即時價(興櫃, "9999", 資料日, 現在=盤中, 抓報價=不該抓)
    if 說明:
        錯誤.append("興櫃沒有證交所即時價，不該套用")

    if 錯誤:
        print("❌ 即時價檢查失敗：\n" + "\n".join(錯誤))
        sys.exit(1)
    print("✅ 個股報告即時價換算正確")


if __name__ == "__main__":
    main()
