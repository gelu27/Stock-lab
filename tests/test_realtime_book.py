# 自動檢查：盤中即時五檔（engine.解析五檔／五檔解讀）、集保 e 存摺匯入（engine.解析存摺／存摺對照）
#   本機執行：python tests/test_realtime_book.py
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import engine  # noqa: E402


def main():
    錯誤 = []

    # ---------- 五檔 ----------
    m = {"c": "2330", "n": "台積電", "z": "1005.0000", "y": "1000.0000", "o": "1001", "h": "1010", "l": "998",
         "u": "1100", "w": "900", "v": "23456", "tv": "12", "t": "10:35:12", "d": "20261116",
         "a": "1005.0000_1010.0000_1015.0000_1020.0000_1025.0000_", "f": "100_50_30_20_10_",
         "b": "1000.0000_995.0000_990.0000_985.0000_980.0000_", "g": "300_200_100_100_100_"}
    五 = engine.解析五檔(m)
    if not 五 or 五["現價"] != 1005 or abs(五["漲跌幅"] - 0.5) > 1e-9:
        錯誤.append(f"五檔現價／漲跌幅不對：{五 and (五['現價'], 五['漲跌幅'])}")
    if 五 and (len(五["買"]) != 5 or 五["買"][0] != (1000.0, 300.0) or 五["賣"][0] != (1005.0, 100.0)):
        錯誤.append("五檔買賣價量拆錯")
    if 五 and (五["委買"] != 800 or 五["委賣"] != 210 or abs(五["買盤比"] - 800 / 1010 * 100) > 1e-9):
        錯誤.append(f"委買委賣合計錯：{五['委買']} {五['委賣']}")
    if "下方掛單較厚" not in engine.五檔解讀(五):
        錯誤.append(f"買盤多時解讀不對：{engine.五檔解讀(五)}")

    沒成交 = {**m, "z": "-"}
    五 = engine.解析五檔(沒成交)
    if not 五 or 五["有成交"] or 五["現價"] != 1002.5:
        錯誤.append("沒成交時應該用買賣中間價")
    漲停 = {**m, "z": "1100", "a": "-", "f": "-", "b": "1100_1095_", "g": "5000_10_"}
    五 = engine.解析五檔(漲停)
    if not 五 or 五["賣"] or "漲停" not in engine.五檔解讀(五):
        錯誤.append("漲停（沒有賣單）處理不對")
    if engine.五檔解讀(None) != "":
        錯誤.append("沒有資料時解讀要是空字串")
    假 = engine.即時五檔("2330", "上市", 抓=lambda 網址: m if "tse_2330.tw" in 網址 else None)
    if not 假 or 假["代號"] != "2330":
        錯誤.append("即時五檔網址（上市 tse_）不對")
    if engine.即時五檔("6488", "上櫃", 抓=lambda 網址: m if "otc_6488.tw" in 網址 else None) is None:
        錯誤.append("即時五檔網址（上櫃 otc_）不對")

    # ---------- e 存摺 ----------
    文字 = """臺灣集中保管結算所 集保e存摺 列印日期 2026/11/15
帳號 9A95-0123456
證券代號 證券名稱 前日餘額 本日餘額
2330 台積電 2,000 3,000
0050 元大台灣50 1,500 1,500
00981A 主動統一台股增長 10,000 10,000
9999 不存在股 100 100
2026/11/14 交易 1234
"""
    已知 = {"2330", "0050", "00981A", "2317"}
    t = engine.解析存摺(文字, 已知代號=已知).set_index("代號")
    預期 = {"2330": 3000, "0050": 1500, "00981A": 10000}
    for 代, 股 in 預期.items():
        if 代 not in t.index or t.at[代, "股數"] != 股:
            錯誤.append(f"PDF 文字 {代} 股數應該是 {股}，得到 {t['股數'].get(代)}")
    if "9999" in t.index or len(t) != 3:
        錯誤.append(f"不認得的代號、日期不該被當成股票：{list(t.index)}")

    表 = pd.DataFrame({"證券代號": ["2330", "2317", "abc"], "證券名稱": ["台積電", "鴻海", "x"], "庫存股數": ["3,000", "500", "1"]})
    t = engine.解析存摺(表, 已知代號=已知).set_index("代號")
    if t["股數"].to_dict() != {"2317": 500.0, "2330": 3000.0}:
        錯誤.append(f"CSV 表格解析不對：{t['股數'].to_dict()}")
    if not engine.解析存摺(pd.DataFrame({"x": [1]})).empty:
        錯誤.append("沒有代號欄的表要回空表")

    現有 = pd.DataFrame({"代號": ["2330", "2317", "0050"], "股數": [2000.0, 1000.0, 1500.0], "總成本": [1_800_000.0, 150_000.0, 90_000.0]})
    新 = pd.DataFrame({"代號": ["2330", "0050", "00981A"], "名稱": ["台積電", "元大台灣50", "主動統一"], "股數": [3000.0, 1500.0, 10000.0]})
    對 = engine.存摺對照(新, 現有, {"00981A": 15.0}).set_index("代號")
    if 對.at["2330", "總成本"] != 2_700_000 or "股數變動" not in 對.at["2330", "狀態"]:
        錯誤.append("股數變動要用原均價換算成本")
    if 對.at["0050", "狀態"] != "相同" or 對.at["0050", "總成本"] != 90_000:
        錯誤.append("股數相同要沿用成本")
    if 對.at["00981A", "總成本"] != 150_000 or "成本請填" not in 對.at["00981A", "狀態"]:
        錯誤.append("新股票要用收盤估成本並提醒")
    if 對.at["2317", "存摺股數"] != 0 or "移除" not in 對.at["2317", "狀態"]:
        錯誤.append("存摺沒有的股票要標出來")
    if not engine.存摺對照(新, pd.DataFrame(columns=["代號", "股數", "總成本"])).shape[0] == 3:
        錯誤.append("網站原本沒庫存時也要能對照")

    if 錯誤:
        print("❌ " + "\n❌ ".join(錯誤))
        sys.exit(1)
    print("✅ 即時五檔、e 存摺匯入檢查通過")


if __name__ == "__main__":
    main()
