# 每日 LINE 推播：80 分以上名單與新增／剔除比對
#   本機執行：python tests/test_score80.py
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import notify

分 = pd.DataFrame({"名稱": ["甲", "乙", "丙", "丁"], "總分": [85.2, 80.0, 79.9, 90.0],
                  "較昨日": [1.0, 3.0, -2.0, np.nan]}, index=["1111", "2222", "3333", "4444"])

# 第一次（沒有存檔）：用較昨日推算昨天 → 昨天 1111(84.2)、3333(81.9) 在榜
行, 存 = notify.高分名單變化(分, "2026-11-09", {})
文 = "\n".join(行)
assert "80 分以上 3 檔" in 文, 文
assert "新增 2 檔" in 文 and "乙" in 文 and "丁" in 文, 文
assert "剔除 1 檔" in 文 and "丙 81.9→79.9" in 文, 文
assert set(存["名單"]) == {"1111", "2222", "4444"} and 存["日期"] == "2026-11-09"

# 隔天：跟存檔比
分2 = 分.assign(總分=[70.0, 82.0, 88.0, 91.0])
行, 存2 = notify.高分名單變化(分2, "2026-11-10", 存, 庫存們={"3333"})
文 = "\n".join(行)
assert "新增 1 檔（比 11/09）：💼丙 88.0" in 文, 文
assert "剔除 1 檔（比 11/09）：甲 85.2→70.0" in 文, 文
assert 存2["前一日"]["日期"] == "2026-11-09"

# 同一天重跑：還是跟 11/09 比，不會變成跟自己比
行, 存3 = notify.高分名單變化(分2, "2026-11-10", 存2)
assert "新增 1 檔（比 11/09）" in "\n".join(行)
assert 存3["前一日"]["日期"] == "2026-11-09"

# 被剔除的股票不在候選（例如量太少）時，從全部分數查現在幾分；完全沒有就寫無資料
行, _ = notify.高分名單變化(分2.drop("1111"), "2026-11-10", 存, 全=分2)
assert "甲 85.2→70.0" in "\n".join(行)
行, _ = notify.高分名單變化(分2.drop("1111"), "2026-11-10", 存)
assert "甲 85.2→無資料" in "\n".join(行)

# 沒有任何股票 80 分以上
行, _ = notify.高分名單變化(分.assign(總分=50.0), "2026-11-10", 存)
assert "80 分以上 0 檔" in "\n".join(行) and "剔除 3 檔" in "\n".join(行)
print("80 分名單測試通過")
